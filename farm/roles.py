def _with_context(body: str, context: str) -> str:
    """Поставить выжимку веб-поиска перед заданием.

    Контекст идёт первым, а не после вопроса, так модель читает факты до
    того, как начнёт отвечать, и не перестраивает уже готовый ответ.
    """

    if not context:
        return body
    return f"{context}\n\n{body}"


