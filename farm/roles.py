def critic_verdict(text: str) -> tuple[bool, str]:
    """Разобрать ответ контролёра.

    «БРАК» ищется подстрокой в строке вердикта, а не сравнением строки
    целиком: иначе ответ «Вердикт: БРАК» прошёл бы как одобрение. Если
    вердикта нет вовсе, ответ считается принятым — иначе ферма зациклится на
    переделках из-за того, что маленькая модель не удержала шаблон. Тот же
    смысл у требования «проверяй только по критериям»: придраться можно
    всегда, а работа должна быть сдана.
    """

    verdict_line = ""
    for line in text.upper().splitlines():
        if "ВЕРДИКТ" in line:
            verdict_line = line
            break
    if not verdict_line:
        return True, ""
    rejected = "БРАК" in verdict_line
    note = ""
    for line in text.splitlines():
        if "ЗАМЕЧАНИЯ" in line.upper():
            note = line.split(":", 1)[-1].strip()
            break
    return (not rejected), note
