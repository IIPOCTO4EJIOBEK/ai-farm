"""Роли и промпты фермы: диспетчер, специалисты по доменам, контролёр.

Файл собран не «на вкус», а по трём источникам, которые стоит держать в
голове при правках:

* Anthropic, prompt engineering — инструкции живут в system, данные в
  пользовательском сообщении, а границы блоков размечены тегами. Отсюда
  везде ``<задача>``/``<подзадача>``/``<ответ>``.
* Схема planner → executor → critic (masterprompting.net, апрель 2026) —
  у критика обязан быть жёсткий формат вердикта, запрет на расплывчатые
  замечания и отдельный список критериев. Диспетчеру нужен явный запрет
  дробить всё подряд: без него модель порождает подзадачи там, где дешевле
  сделать работу целиком.
* Разбор анти-паттернов мультиагентных схем (sureprompts) — «общий контекст
  везде», «у воркеров одинаковое вступление», «воркеры переделывают работу
  друг друга», «нет схемы передачи». Поэтому у каждого домена своя персона,
  свой контракт вывода и свои критерии приёмки, а исполнитель получает
  только свою подзадачу, а не всю переписку.

Отдельная тонкость: половина пула — модели на 3–7 млрд параметров. Им нужны
короткие однозначные требования и жёсткий шаблон ответа; нюансы и «прояви
вкус» они проваливают. Поэтому промпты выглядят директивно — это осознанно.
"""

from __future__ import annotations

from dataclasses import dataclass


# ----------------------------------------------------------------------
# Домены: кто исполнитель, что ему запрещено и по чему его принимают
# ----------------------------------------------------------------------


@dataclass(frozen=True)
class Domain:
    """Специализация исполнителя."""

    key: str
    title: str
    keywords: tuple[str, ...]
    persona: str
    rules: tuple[str, ...]
    contract: str
    criteria: tuple[str, ...]

    def worker_system(self) -> str:
        rules = "\n".join(f"{i}. {rule}" for i, rule in enumerate(self.rules, 1))
        return (
            f"{self.persona}\n\n"
            f"<обязательные_правила>\n{rules}\n</обязательные_правила>\n\n"
            f"<контракт_вывода>\n{self.contract}\n</контракт_вывода>"
        )

    def critic_system(self) -> str:
        criteria = "\n".join(f"{i}. {c}" for i, c in enumerate(self.criteria, 1))
        return (
            f"Ты контролёр качества в области «{self.title}».\n\n"
            f"<критерии_приёмки>\n{criteria}\n</критерии_приёмки>\n\n"
            f"{CRITIC_FORMAT}"
        )


CRITIC_FORMAT = """Формат ответа строго такой, без вступлений и без markdown:

ВЕРДИКТ: ОК
или
ВЕРДИКТ: БРАК
ЗАМЕЧАНИЯ: <что именно нарушено и что сделать вместо этого>

Требования к замечанию:
- запрещены формулировки «можно улучшить», «неплохо бы», «стоит доработать»;
- указывай конкретное нарушенное требование и конкретное исправление;
- проверяй только по критериям выше: если ответ им соответствует — ОК,
  даже если он неидеален. Идеальность не требуется, требуется пригодность."""


