DOMAINS: tuple[Domain, ...] = (
    ONEC, TRADING, SQL, WEB, DEVOPS, SLIDES, CODE, DOCS,
)

_BY_KEY = {domain.key: domain for domain in DOMAINS}
_BY_KEY[GENERAL.key] = GENERAL


def domain_by_key(key: str) -> Domain:
    return _BY_KEY.get((key or "").strip().lower(), GENERAL)


def route(text: str, *, default: Domain = GENERAL) -> Domain:
    """Определить домен по тексту задачи.

    Разбор идёт по ключевым словам, а не моделью: это бесплатно, мгновенно
    и предсказуемо. Домен нужен, чтобы исполнитель получил свою персону и
    свой контракт вывода, — ошибка в выборе домена стоит меньше, чем лишний
    вызов модели на классификацию.

    Домены идут от узкого к широкому, и при равенстве баллов выигрывает
    тот, что стоит раньше: «запрос 1С к справочнику» — это 1С, а не SQL.
    """

    haystack = " " + text.lower().replace("ё", "е") + " "
    best, best_score = default, 0
    for domain in DOMAINS:
        score = sum(1 for word in domain.keywords if word.replace("ё", "е") in haystack)
        if score > best_score:
            best, best_score = domain, score
    return best


